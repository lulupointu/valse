import CoreGraphics
import Foundation
import MontageCore
import MontageEngine

/// Synthetic media generated on demand into a per-user temp cache (reused across runs by content key).
public enum TestMedia {
    /// `MONTAGE_TEST_MEDIA_DIR` (set by scripts/test.sh, which runs tests in a private TMPDIR removed afterwards) keeps
    /// the cache in the machine temp dir across runs.
    public static let directory: URL = {
        let env = ProcessInfo.processInfo.environment["MONTAGE_TEST_MEDIA_DIR"].flatMap { $0.isEmpty ? nil : $0 }
        let d = env.map { URL(fileURLWithPath: $0, isDirectory: true) }
            ?? FileManager.default.temporaryDirectory.appendingPathComponent("montage-test-media-v1", isDirectory: true)
        try? FileManager.default.createDirectory(at: d, withIntermediateDirectories: true)
        return d
    }()

    /// Video file with `pattern`. Cached by parameters.
    public static func video(_ pattern: SyntheticMedia.Pattern, seconds: Double = 2, size: CGSize = CGSize(width: 320, height: 180),
                             fps: Int32 = 30, codec: SyntheticMedia.Codec = .h264, audioHz: Double? = nil) async throws -> URL {
        let key = "\(pattern)-\(seconds)-\(Int(size.width))x\(Int(size.height))-\(fps)-\(codec)-\(audioHz ?? 0)"
        let ext = codec == .proRes422 ? "mov" : "mp4"
        let url = directory.appendingPathComponent("v-\(stableHash(key)).\(ext)")
        return try await cached(url) { tmp in
            try await SyntheticMedia.writeVideo(to: tmp, size: size, seconds: seconds, fps: fps, codec: codec, pattern: pattern, audioHz: audioHz)
        }
    }

    public static func image(_ pattern: SyntheticMedia.Pattern, size: CGSize = CGSize(width: 320, height: 320)) throws -> URL {
        let url = directory.appendingPathComponent("i-\(stableHash("\(pattern)-\(size)")).png")
        // written beside, then renamed: a concurrent run (another checkout shares this cache) never reads a partial PNG
        return try cachedSync(url) { tmp in try SyntheticMedia.writePNG(to: tmp, size: size, pattern: pattern) }
    }

    public static func audio(seconds: Double = 2, hz: Double = 440) async throws -> URL {
        let url = directory.appendingPathComponent("a-\(stableHash("\(seconds)-\(hz)")).m4a")
        return try await cached(url) { tmp in try await SyntheticMedia.writeAudio(to: tmp, seconds: seconds, hz: hz) }
    }

    /// The cache file `url`, generated by `write(tmp)` when missing. The cache is shared by every checkout's runs at
    /// once, so a file is written beside it and renamed into place (atomic: readers see all of it or nothing), and a
    /// cached file that is empty (an old non-atomic writer's leftover: a 0-byte `face-walk-v1.mov` crashed every unit
    /// run) is regenerated. A failed write is retried twice: AVAssetWriter's encoder fails now and then on a loaded
    /// machine (VideoToolbox), which is not what the calling test checks.
    public static func cached(_ url: URL, ext: String? = nil, attempts: Int = 3,
                              _ write: (URL) async throws -> Void) async throws -> URL {
        if isUsable(url) { return url }
        var lastError: Error?
        for attempt in 1...max(1, attempts) {
            let tmp = directory.appendingPathComponent("tmp-\(UUID().uuidString).\(ext ?? url.pathExtension)")
            do {
                try await write(tmp)
                guard isUsable(tmp) else { throw NSError(domain: "TestMedia", code: 1, userInfo: [NSLocalizedDescriptionKey: "empty output"]) }
                publish(tmp, as: url)
                return url
            } catch {
                try? FileManager.default.removeItem(at: tmp)
                if error is CancellationError { throw error }
                lastError = error
                print("TestMedia: generating \(url.lastPathComponent) failed (attempt \(attempt)): \(error)")
                if isUsable(url) { return url }   // a concurrent run produced it meanwhile
                if attempt < attempts { try await Task.sleep(nanoseconds: UInt64(attempt) * 300_000_000) }
            }
        }
        throw lastError ?? NSError(domain: "TestMedia", code: 2)
    }

    /// Synchronous `cached` (stills drawn with Core Graphics): same atomic publish, no retry.
    public static func cachedSync(_ url: URL, _ write: (URL) throws -> Void) throws -> URL {
        if isUsable(url) { return url }
        let tmp = directory.appendingPathComponent("tmp-\(UUID().uuidString).\(url.pathExtension)")
        defer { try? FileManager.default.removeItem(at: tmp) }
        try write(tmp)
        guard isUsable(tmp) else { throw NSError(domain: "TestMedia", code: 1, userInfo: [NSLocalizedDescriptionKey: "empty output for \(url.lastPathComponent)"]) }
        publish(tmp, as: url)
        return url
    }

    /// A cache entry exists and is not empty.
    public static func isUsable(_ url: URL) -> Bool {
        ((try? FileManager.default.attributesOfItem(atPath: url.path)[.size] as? Int) ?? 0) > 0
    }

    /// Renames the finished `tmp` onto `url` (rename(2) replaces atomically; a concurrent identical result is fine).
    public static func publishFile(_ tmp: URL, as url: URL) { publish(tmp, as: url) }

    static func publish(_ tmp: URL, as url: URL) {
        if rename(tmp.path, url.path) != 0 { try? FileManager.default.removeItem(at: tmp) }
    }

    /// FNV-1a (String.hashValue is randomized per process).
    static func stableHash(_ s: String) -> String {
        var h: UInt64 = 0xcbf29ce484222325
        for b in s.utf8 { h = (h ^ UInt64(b)) &* 0x100000001b3 }
        return String(h, radix: 16)
    }

    /// Repo-relative path helper (bench media etc.).
    public static func repoRoot(file: String = #filePath) -> URL {
        var u = URL(fileURLWithPath: file)
        while u.path != "/" {
            u.deleteLastPathComponent()
            if FileManager.default.fileExists(atPath: u.appendingPathComponent("Package.swift").path),
               FileManager.default.fileExists(atPath: u.appendingPathComponent("docs").path) { return u }
        }
        return URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
    }
}
